// Run from repository root; regenerates only static server copy from reviewed app catalogs.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
const folder = path.join(root, "mobile/assets/l10n");
const source = fs.readFileSync(
  path.join(root, "backend/api/src/customers/customer-experience.service.ts"),
  "utf8",
);
const value = (name) => {
  const m = source.match(
    new RegExp("export const " + name + ' =\\s*"([^"\\n]+)"'),
  );
  if (!m) throw new Error(name);
  return m[1];
};
const photo = value("CUSTOMER_PHOTO_CONSENT"),
  store = value("CUSTOMER_STORE_CONSENT");
const copy = {};
for (const file of fs
  .readdirSync(folder)
  .filter((file) => file.endsWith(".json"))
  .sort()) {
  const language = file.slice(0, -5),
    d = JSON.parse(fs.readFileSync(path.join(folder, file), "utf8"));
  copy[language] = {
    title: d["Your look is ready"],
    body: d["Open your saved Try-On."],
    pushBody: d["Open SelfX to view your saved Try-On."],
    photoConsent: d[photo],
    storeConsent: d[store],
  };
  if (
    Object.values(copy[language]).some(
      (item) => typeof item !== "string" || !item.trim(),
    )
  )
    throw new Error("Incomplete copy " + language);
}
const output =
  "// Generated by mobile/tool/generate_backend_copy.mjs from bundled UI catalogs.\nconst copy = " +
  JSON.stringify(copy, null, 2) +
  ' as const;\nexport const CUSTOMER_TRANSLATION_VERSION = "2026-10-27";\nexport function customerNotificationCopy(language?: string) {\n const key = language && Object.hasOwn(copy, language) ? language as keyof typeof copy : "en";\n return copy[key];\n}\n';
fs.writeFileSync(
  path.join(root, "backend/api/src/customers/customer-notification-copy.ts"),
  output,
);
