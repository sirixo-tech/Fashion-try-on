class TryOnResultScreen extends StatelessWidget {
  const TryOnResultScreen({
    super.key,
    required this.captureController,
    required this.tryOnController,
    required this.uploadController,
  });

  final CaptureSessionController captureController;
  final KioskTryOnSessionController tryOnController;
  final KioskCustomerUploadController uploadController;

  @override
  Widget build(BuildContext context) {
    final result = tryOnController.result;
    return KioskScaffold(
      title: 'Your Try-On',
      subtitle: 'Generated by SelfX',
      child: result == null
          ? const Center(child: Text('Try-On result unavailable.'))
          : LayoutBuilder(
              builder: (context, constraints) {
                final portrait =
                    constraints.maxHeight > constraints.maxWidth * 1.12;
                final compact =
                    constraints.maxWidth < 920 ||
                    constraints.maxHeight < 620 ||
                    portrait;
                final image = Card(
                  child: ClipRRect(
                    borderRadius: BorderRadius.circular(10),
                    child: _GeneratedTryOnImage(src: result.generatedImage),
                  ),
                );
                final actions = _ResultActions(
                  compact: compact,
                  onTryAnotherGarment: () => _tryAnotherGarment(context),
                  onRetakePhoto: () => _retakePhoto(context),
                  onFinish: () => _finish(context),
                );

                if (compact) {
                  return SingleChildScrollView(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.stretch,
                      children: [
                        SizedBox(
                          height: portrait
                              ? constraints.maxHeight * 0.58
                              : constraints.maxWidth * 0.58,
                          child: image,
                        ),
                        const SizedBox(height: 18),
                        actions,
                      ],
                    ),
                  );
                }

                return Row(
                  crossAxisAlignment: CrossAxisAlignment.stretch,
                  children: [
                    Expanded(child: image),
                    const SizedBox(width: 24),
                    SizedBox(width: 420, child: actions),
                  ],
                );
              },
            ),
    );
  }

  void _tryAnotherGarment(BuildContext context) {
    tryOnController.tryAnotherGarment();
    Navigator.of(context).pushAndRemoveUntil(
      MaterialPageRoute<void>(
        builder: (_) => GarmentSelectionScreen(
          captureController: captureController,
          tryOnController: tryOnController,
          uploadController: uploadController,
        ),
      ),
      (route) => route.isFirst,
    );
  }

  Future<void> _retakePhoto(BuildContext context) async {
    await tryOnController.retakePhoto(captureController);
    if (!context.mounted) {
      return;
    }
    Navigator.of(context).pushAndRemoveUntil(
      MaterialPageRoute<void>(
        builder: (_) => PhotoSourceChoiceScreen(
          captureController: captureController,
          tryOnController: tryOnController,
          uploadController: uploadController,
        ),
      ),
      (route) => route.isFirst,
    );
  }

  Future<void> _finish(BuildContext context) async {
    await tryOnController.finish(captureController);
    if (context.mounted) {
      Navigator.of(context).popUntil((route) => route.isFirst);
    }
  }
}

class _GeneratedTryOnImage extends StatelessWidget {
  const _GeneratedTryOnImage({required this.src});

  final String src;

  @override
  Widget build(BuildContext context) {
    if (src.startsWith('data:image/')) {
      final bytes = _decodeDataImage(src);
      if (bytes == null) {
        return const Center(child: Text('Generated image unavailable'));
      }
      return Image.memory(
        bytes,
        fit: BoxFit.contain,
        errorBuilder: (_, _, _) =>
            const Center(child: Text('Generated image unavailable')),
      );
    }
    if (!src.startsWith('http://') && !src.startsWith('https://')) {
      final bytes = _decodeBase64Image(src);
      if (bytes == null) {
        return const Center(child: Text('Generated image unavailable'));
      }
      return Image.memory(
        bytes,
        fit: BoxFit.contain,
        errorBuilder: (_, _, _) =>
            const Center(child: Text('Generated image unavailable')),
      );
    }
    return Image.network(
      src,
      fit: BoxFit.contain,
      errorBuilder: (_, _, _) =>
          const Center(child: Text('Generated image unavailable')),
    );
  }

  Uint8List? _decodeDataImage(String value) {
    try {
      return UriData.parse(value).contentAsBytes();
    } catch (_) {
      return null;
    }
  }

  Uint8List? _decodeBase64Image(String value) {
    try {
      return base64Decode(value);
    } catch (_) {
      return null;
    }
  }
}

